#!/bin/bash

# ========================================================
# [교육용 주석] LSTM 모델 백그라운드 무한 루프 재학습 스크립트 (Daemon형)
# ========================================================
# 1. 데몬(Daemon)이란?
#    - 사용자가 직접 제어하지 않고, 백그라운드에서 여러 작업을 하는 프로그램을 말합니다.
#    - 이 스크립트는 종료되지 않고 계속 백그라운드(서버 뒷단)에 떠서 지정된 시간마다 
#      어떤 동작(학습)을 수행하게 해주는 역할을 합니다.
#
# 2. 실행 방법:
#    nohup bash daemon_retrain_lstm.sh > daemon_retrain.log 2>&1 &
#    - `nohup`: 사용자가 터미널 접속을 끊어도 프로세스가 죽지 않고 계속 돌게 해주는 명령어
#    - `> daemon_retrain.log`: 실행되면서 찍히는 로그(echo 등)를 파일로 저장
#    - `2>&1`: 에러 메시지도 일반 로그 파일에 같이 기록하라는 뜻
#    - `&`: 프로세스를 백그라운드로 실행하라는 뜻
# ========================================================

# 변수 선언: 프로젝트의 절대 경로와 실행할 스크립트의 경로를 지정합니다.
# 절대 경로를 명시하는 이유는 cron이나 데몬 등 백그라운드 환경에서는 현재 위치(pwd)나 상대 경로(./)가 
# 우리가 기대하는 위치와 다를 수 있기 때문입니다.
PROJECT_DIR="/home/j-j14b110/smart_home_ai/server_ai"
CRON_SCRIPT="$PROJECT_DIR/recommendation/scripts/cron_retrain_lstm.sh"

echo "[$(date '+%Y-%m-%d %H:%M:%S')] 백그라운드 LSTM 학습 데몬을 시작합니다."

# 무한 루프 시작 (while true)
# 이 블록 안에 있는 코드는 스크립트나 프로세스가 강제로 종료될 때까지 무한히 반복됩니다.
while true; do
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] 재학습 스크립트 트리거"
    
    # 실제 학습을 수행하는 스크립트(위에서 정의한 CRON_SCRIPT)를 실행(호출)합니다.
    # 이렇게 스크립트를 분리하면, 데몬(시간 관리)과 로직(학습)을 분리하여 각자 유지보수하기 좋습니다.
    bash "$CRON_SCRIPT"
    
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] ✅ 트리거 완료. 다음 학습까지 24시간을 대기합니다..."
    
    # 24시간(86400초) 동안 대기
    # sleep 명령어를 사용해 프로세스를 주어진 초만큼 멈춥니다.
    # 86400초가 지나면 다시 while 루프의 처음으로 돌아가서 스크립트를 재호출합니다.
    sleep 86400
done
